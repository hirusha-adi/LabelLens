"""Builds the web fonts in public/fonts and the icon map in src/lib/icons.ts.

The site hosts its own fonts so that opening it sends nothing to a font service.

Needs fonttools and brotli (`pip install fonttools brotli`). Arguments:
  1. a folder holding symbols.ttf and symbols.codepoints (Material Symbols Rounded
     variable font and its codepoints file, from github.com/google/material-design-icons,
     variablefont/), and jetbrains.ttf (JetBrains Mono variable, from github.com/google/fonts)
  2. the Android app's font folder (android/app/src/main/res/font), for Gabarito and Hanken Grotesk
  3. the www folder

To use a new icon, add its name to ICONS below and run this again.
"""
import os, sys
from fontTools import subset
from fontTools.ttLib import TTFont

ICONS = """add android arrow_back arrow_forward block bookmark bookmark_add bubble_chart check check_circle
chevron_right child_care close code crop dark_mode database delete_sweep description document_scanner
download eco egg_alt expand_less expand_more forest gavel grain help history home info inventory_2 labs
language license light_mode lightbulb local_fire_department more_vert mosque notifications open_in_new
palette person person_alert photo_library policy pregnant_woman priority_high pulmonology restaurant
restore rotate_right science search search_off set_meal settings share shield_lock shopping_basket spa
synagogue sync_problem text_select_start tune upload verified_user volunteer_activism warning water_drop
edit link content_copy""".split()

downloads, android_fonts, www = sys.argv[1:4]
out = os.path.join(www, "public", "fonts")
os.makedirs(out, exist_ok=True)

LATIN = "U+0020-007E,U+00A0-00FF,U+2013,U+2014,U+2018,U+2019,U+201C,U+201D,U+2022,U+2026,U+2192,U+2212,U+00B5,U+221E,U+2713"

def write(source, name, unicodes=None, text_unicodes=None):
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = ["*"] if text_unicodes else []
    options.notdef_outline = True
    font = subset.load_font(source, options)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=unicodes or subset.parse_unicodes(text_unicodes))
    subsetter.subset(font)
    path = os.path.join(out, name)
    subset.save_font(font, path, options)
    print(f"{name}: {os.path.getsize(path) // 1024} KB")

codepoints = dict(line.split() for line in open(os.path.join(downloads, "symbols.codepoints")) if line.strip())
missing = [name for name in ICONS if name not in codepoints]
if missing:
    sys.exit(f"Not in Material Symbols Rounded: {', '.join(missing)}")

write(os.path.join(downloads, "symbols.ttf"), "material-symbols-rounded.woff2", unicodes=[int(codepoints[n], 16) for n in ICONS])
write(os.path.join(android_fonts, "gabarito.ttf"), "gabarito.woff2", text_unicodes=LATIN)
write(os.path.join(android_fonts, "hanken_grotesk.ttf"), "hanken-grotesk.woff2", text_unicodes=LATIN)
write(os.path.join(downloads, "jetbrains.ttf"), "jetbrains-mono.woff2", text_unicodes="U+0020-007E")

lines = [
    "// Generated by scripts/build-fonts.py. Do not edit by hand.",
    "",
    "/** Icon name to glyph in the Material Symbols Rounded subset in public/fonts. */",
    "export const ICONS = {",
]
for name in sorted(ICONS):
    lines.append(f'  {name}: "\\u{{{codepoints[name].upper()}}}",')
lines += ["} as const;", "", "export type IconName = keyof typeof ICONS;", ""]
open(os.path.join(www, "src", "lib", "icons.ts"), "w").write("\n".join(lines))
print(f"{len(ICONS)} icons")
